-- Run against Postgres after the migration. All fixture rows roll back.
begin;
create function pg_temp.assert_true(value boolean, message text) returns void language plpgsql as $$ begin if value is distinct from true then raise exception 'ASSERTION FAILED: %',message; end if; end $$;
do $$
declare
  h jsonb; r text; token uuid; initial_cp text := 'cp-original';
  b text := 'followup-acceptance-'||gen_random_uuid()::text;
  a text; e jsonb; failed boolean;
begin
  h := public.followup_mutate(b,'seed','{}',jsonb_build_object('status','In Progress','ownerId','am-peter','ownerName','Peter','currentCpId',initial_cp));
  r := h->'rounds'->0->>'id';
  perform pg_temp.assert_true(h->'rounds'->0->>'status'='Active','Legacy active Round');
  perform pg_temp.assert_true(h->'rounds'->0->>'started_at' is null,'No fabricated legacy start date');
  e := jsonb_build_object('id',b||'-enc1','exhibitionId','show-1','exhibitionName','SUPERZOO','meetingAt','2026-08-13T12:00:00Z','metBy','Ella','meetingNotes','Original notes','keyChanges','[]'::jsonb);
  h := public.followup_mutate(b,'encounter',e);
  perform pg_temp.assert_true(h->'encounters'->0->>'round_id'=r,'Active Encounter links current Round');
  perform pg_temp.assert_true(h->'rounds'->0->>'current_cp'=initial_cp,'Encounter preserves CP');
  perform pg_temp.assert_true(h->'rounds'->0->>'assigned_am_id'='am-peter','Encounter preserves AM');
  h := public.followup_mutate(b,'encounter',e);
  perform pg_temp.assert_true((h->>'duplicate')::boolean and jsonb_array_length(h->'encounters')=1,'Stable Encounter retry deduplicates');
  failed := false;
  begin perform public.followup_mutate(b,'encounter',e||'{"meetingNotes":"Changed"}'); exception when sqlstate 'P0001' then failed:=true; end;
  perform pg_temp.assert_true(failed,'Conflicting replay rejected');
  h := public.followup_mutate(b,'encounter',e||jsonb_build_object('id',b||'-enc2','exhibitionId','show-2','exhibitionName','Newtopia','keyChanges',jsonb_build_array(jsonb_build_object('type','Interest','text','New product interest','source',b||'-enc2'))));
  perform pg_temp.assert_true(jsonb_array_length(h->'rounds')=1 and jsonb_array_length(h->'encounters')=2,'Multiple Encounters same Round');
  perform pg_temp.assert_true((select count(*)=1 from public.system_notifications where brand_id=b),'Only significant Encounter notifies AM');
  h := public.followup_mutate(b,'patch','{"ownerId":"am-ella","ownerName":"Ella","changedBy":"Admin"}');
  perform pg_temp.assert_true(h->'rounds'->0->>'id'=r and h->'rounds'->0->>'current_cp'=initial_cp,'Reassignment retains Round and CP');
  perform pg_temp.assert_true(h->'assignments'->0->>'previous_am_id'='am-peter' and h->'assignments'->0->>'new_am_id'='am-ella','AM audit captures previous and new owner');
  failed:=false;
  begin perform public.followup_mutate(b,'start','{}'); exception when sqlstate 'P0001' then failed:=true; end;
  perform pg_temp.assert_true(failed,'Pending projection blocks concurrent mutation');
  token:=(public.followup_projection(b,'claim')->>'token')::uuid;
  perform pg_temp.assert_true(public.followup_projection(b,'claim') is null,'Only one projector claims work');
  perform public.followup_projection(b,'ack',token);
  h := public.followup_mutate(b,'patch','{"status":"Paused","note":"Budget review"}');
  token:=(public.followup_projection(b,'claim')->>'token')::uuid; perform public.followup_projection(b,'ack',token);
  h := public.followup_mutate(b,'encounter',e||jsonb_build_object('id',b||'-enc3'));
  perform pg_temp.assert_true(h->'rounds'->0->>'status'='Paused','Encounter does not Resume');
  h := public.followup_mutate(b,'resume','{}');
  perform pg_temp.assert_true(h->'rounds'->0->>'id'=r and h->'rounds'->0->>'current_cp'=initial_cp,'Resume retains identity and CP');
  token:=(public.followup_projection(b,'claim')->>'token')::uuid; perform public.followup_projection(b,'ack',token);
  failed:=false;
  begin perform public.followup_mutate(b,'start','{}'); exception when sqlstate 'P0001' then failed:=true; end;
  perform pg_temp.assert_true(failed,'Active Round cannot start another');
  h := public.followup_mutate(b,'patch','{"status":"Completed","note":"Customer not ready"}');
  token:=(public.followup_projection(b,'claim')->>'token')::uuid; perform public.followup_projection(b,'ack',token);
  failed:=false;
  begin perform public.followup_mutate(b,'resume','{}'); exception when sqlstate 'P0001' then failed:=true; end;
  perform pg_temp.assert_true(failed,'Completed Round cannot Resume');
  failed:=false;
  begin perform public.followup_mutate(b,'patch','{"status":"In Progress"}'); exception when sqlstate 'P0001' then failed:=true; end;
  perform pg_temp.assert_true(failed,'Status patch cannot reopen Completed Round');
  h := public.followup_mutate(b,'encounter',e||jsonb_build_object('id',b||'-enc4'));
  perform pg_temp.assert_true(h->'encounters'->3->>'round_id' is null and jsonb_array_length(h->'rounds')=1,'Completed Encounter stays unassociated');
  h := public.followup_mutate(b,'start',jsonb_build_object('ownerId','am-new','ownerName','New AM','originEncounterId',b||'-enc4'));
  perform pg_temp.assert_true(h->'rounds'->0->>'round_number'='2' and h->'rounds'->0->>'current_cp' is null,'New Round starts at NONE');
  perform pg_temp.assert_true(h->'rounds'->1->>'assigned_am_id'='am-ella' and h->'rounds'->1->>'outcome'='Customer not ready','Historical AM and outcome preserved');
  perform pg_temp.assert_true(h->'rounds'->0->>'assigned_am_id'='am-new','New AM independent of prior Round');
  token:=(public.followup_projection(b,'claim')->>'token')::uuid; perform public.followup_projection(b,'ack',token);
  failed:=false;
  begin perform public.followup_mutate(b,'patch','{"ownerId":"stale","expectedVersion":0}'); exception when sqlstate 'P0001' then failed:=true; end;
  perform pg_temp.assert_true(failed,'Stale version rejected');
  failed:=false;
  begin insert into public.followup_rounds(brand_id,round_number,status) values(b,3,'Paused'); exception when unique_violation then failed:=true; end;
  perform pg_temp.assert_true(failed,'Database enforces at most one unfinished Round');
  a:=b||'-ready';
  h:=public.followup_mutate(a,'seed','{}','{"status":"Ready","currentCpId":"cp1"}');
  perform pg_temp.assert_true(jsonb_array_length(h->'rounds')=0,'Unstarted Brand has no fabricated Round');
  h:=public.followup_mutate(a,'encounter',e||jsonb_build_object('id',a||'-enc1'));
  perform pg_temp.assert_true(h->'encounters'->0->>'round_id' is null,'Encounter alone never starts Round');
  failed:=false;
  begin perform public.followup_mutate(a,'encounter',e); exception when sqlstate 'P0001' then failed:=true; end;
  perform pg_temp.assert_true(failed,'Same Encounter cannot be linked to another Brand');
end;
$$;
select 'PASS: lifecycle, preservation, retries, reassignment, projection claims, stale writes and unique constraints' as result;
rollback;
